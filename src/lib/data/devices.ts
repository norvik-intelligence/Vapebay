export const deviceBySlug = (slug: string) => DEVICES.find((d) => d.slug === slug);

export const refillableDevices = () => DEVICES.filter((d) => d.podFamily !== 'disposable');

/**
 * URL-safe coil segment, e.g. 0.6 → "0-6-ohm-pod".
 *
 * `toFixed(1)` is load-bearing: `String(1.0)` is `"1"`, which would emit
 * "1-ohm-pod" and never round-trip back through `parseCoilSegment`. Every
 * device with a 1.0 Ohm option would build a page that 404s on request.
 */
export const coilSegment = (ohm: number) => `${ohm.toFixed(1).replace('.', '-')}-ohm-pod`;

/**
 * Inverse of `coilSegment`. Returns null on anything malformed.
 * The decimal group is optional so a hand-typed or previously-published
 * "1-ohm-pod" still resolves instead of 404ing.
 */
export const parseCoilSegment = (segment: string): number | null => {
  const match = /^(\d+)(?:-(\d+))?-ohm-pod$/.exec(segment);
  if (!match) return null;
  const value = Number(`${match[1]}.${match[2] ?? '0'}`);
  return Number.isFinite(value) ? value : null;
};
